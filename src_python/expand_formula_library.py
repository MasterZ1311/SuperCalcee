def expand_and_validate():
    PACKS_DIR.mkdir(parents=True, exist_ok=True)
    all_ids = set()
    total_formulas = 0

    print("=== Expanding SuperCalcee Formula Pack Library ===")

    for filename, formulas in PACK_DATA.items():
        pack_path = PACKS_DIR / filename
        print(f"\nProcessing {filename} ({len(formulas)} formulas):")

        for f in formulas:
            # 1. Check ID uniqueness
            fid = f["id"]
            if fid in all_ids:
                raise ValueError(f"Duplicate formula ID detected: {fid}")
            all_ids.add(fid)

            # 2. Check required fields
            assert f["name"], f"Formula {fid} missing name"
            assert f["desc"], f"Formula {fid} missing desc"
            assert f["expression"], f"Formula {fid} missing expression"
            assert f["unit"], f"Formula {fid} missing unit"
            assert isinstance(f["variables"], list) and len(f["variables"]) > 0, f"Formula {fid} invalid variables"

            # 3. Print verification
            print(f"  ✓ [{fid}] {f['name']} ({f['unit']})")

        total_formulas += len(formulas)

        # Write clean JSON
        with open(pack_path, "w", encoding="utf-8") as out:
            json.dump(formulas, out, indent=2, ensure_ascii=False)

    print(f"\n[SUCCESS] All {len(PACK_DATA)} packs generated successfully!")
    print(f"[TOTAL FORMULAS IN PACKS]: {total_formulas}")


if __name__ == "__main__":
    expand_and_validate()
